#!/bin/sh
# Generate LOCAL-ONLY credentials for the Zurii development database and wire
# them into the three gitignored env files:
#
#   infra/local-db/.env    container superuser + the two app-role passwords
#   backend/.env           DATABASE_URL -> zurii_dev   (the local API)
#   backend/.env.test      TEST_DATABASE_URL -> zurii_test (the guarded test runner)
#
# Rules:
#   - never prints a secret;
#   - never overwrites an existing file (delete one deliberately to regenerate);
#   - every file is created with mode 600.
#
# NOTE: a database volume keeps the passwords it was FIRST initialised with.
# If you regenerate infra/local-db/.env, also remove the volume
# (docker volume rm zurii_local_pgdata — this deletes local data) or the new
# passwords will not match.
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
DB_ENV="$ROOT/infra/local-db/.env"
BACKEND_ENV="$ROOT/backend/.env"
TEST_ENV="$ROOT/backend/.env.test"

command -v openssl >/dev/null 2>&1 || { echo "openssl is required" >&2; exit 1; }
umask 077
gen() { openssl rand -hex "$1"; }

if [ -e "$DB_ENV" ]; then
  echo "• keeping existing infra/local-db/.env"
else
  {
    echo "ZURII_LOCAL_PG_PORT=${ZURII_LOCAL_PG_PORT:-55432}"
    echo "ZURII_LOCAL_PG_SUPERUSER_PASSWORD=$(gen 32)"
    echo "ZURII_DEV_DB_PASSWORD=$(gen 32)"
    echo "ZURII_TEST_DB_PASSWORD=$(gen 32)"
  } > "$DB_ENV"
  echo "✓ wrote infra/local-db/.env"
fi

# Values are read into shell variables only — nothing below echoes them.
# shellcheck disable=SC1090
. "$DB_ENV"
PORT="${ZURII_LOCAL_PG_PORT:-55432}"

if [ -e "$BACKEND_ENV" ]; then
  echo "• keeping existing backend/.env — make sure DATABASE_URL points at zurii_dev on 127.0.0.1:$PORT"
else
  {
    echo "# LOCAL DEVELOPMENT ONLY — generated by infra/local-db/bootstrap-env.sh"
    echo "DATABASE_URL=postgres://zurii_dev_app:${ZURII_DEV_DB_PASSWORD}@127.0.0.1:${PORT}/zurii_dev"
    echo "DATABASE_SSL=disable"
    echo "JWT_SECRET=$(gen 48)"
    echo "JWT_REFRESH_SECRET=$(gen 48)"
    echo "PORT=5001"
    echo "NODE_ENV=development"
  } > "$BACKEND_ENV"
  echo "✓ wrote backend/.env (zurii_dev)"
fi

if [ -e "$TEST_ENV" ]; then
  echo "• keeping existing backend/.env.test"
else
  {
    echo "# AUTOMATED TESTS ONLY — generated by infra/local-db/bootstrap-env.sh"
    echo "# Read only by backend/scripts/run-tests.mjs; never falls back to DATABASE_URL."
    echo "TEST_DATABASE_URL=postgres://zurii_test_app:${ZURII_TEST_DB_PASSWORD}@127.0.0.1:${PORT}/zurii_test"
    echo "DATABASE_SSL=disable"
    echo "JWT_SECRET=$(gen 48)"
    echo "JWT_REFRESH_SECRET=$(gen 48)"
  } > "$TEST_ENV"
  echo "✓ wrote backend/.env.test (zurii_test)"
fi

echo "Done. Next: docker compose -f infra/local-db/compose.yml up -d --wait"
